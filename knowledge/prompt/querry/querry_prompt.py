#商品名确认提示词模板

ITEM_NAME_EXTRACT_TEMPLATE = """
历史会话：
{history_text}

当前用户问题：{query}

请提取用户在【当前这条问题】中正在询问的具体产品名称/型号（item_names）。
1. 只提取当前问题中明确提到的、或用代词（"这个"、"它"、"那款"等）直接指代的产品名称、型号。每项只保留一次，不能重复。
2. 历史会话仅用于消解代词指代；历史上出现过的产品，如果当前问题没有明确提到或指代，【不要】提取进来。
3. 只有当用户明确在比较两个产品（如"XX和YY哪个…"）时，才提取多个产品名。
4. 【不要】把"安全手册"、"说明书"、"资料"、"话题"、"领域"等文件类型/通用词当作 item_names 提取。
5. 如果无法确定具体产品，item_names 返回空列表。
6. 请重新改写用户的问题（rewritten_query），使其成为包含 item_names、独立完整、且保持原意图（询问/对比/确认等）的问题；若指代了历史产品也请写明产品名。

请直接返回JSON格式结果，格式如下：
{{
    "item_names": ["item A", "item B"],
    "rewritten_query": "关于商品A和商品B，..."
}}"""